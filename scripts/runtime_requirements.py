#!/usr/bin/env python3
"""Select the proxy's open-source runtime dependencies from the reviewed source."""
import argparse
import tomllib
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source', type=Path, default=Path('upstream/litellm'))
parser.add_argument('--output', type=Path, default=Path('runtime/requirements.in'))
args=parser.parse_args()
project=tomllib.loads((args.source/'pyproject.toml').read_text())['project']
extras=project['optional-dependencies']
deps=project['dependencies'] + extras['proxy'] + extras['extra_proxy']
deps=[d for d in deps if not d.startswith(('litellm-enterprise', 'litellm-proxy-extras'))]
deps+=tomllib.loads((args.source/'litellm-proxy-extras/pyproject.toml').read_text())['project']['dependencies']
args.output.parent.mkdir(parents=True,exist_ok=True)
args.output.write_text('# Generated by scripts/runtime_requirements.py; local LiteLLM and proxy-extras are built from reviewed source.\n'+'\n'.join(sorted(set(deps)))+'\n')
